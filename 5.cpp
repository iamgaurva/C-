//Input two integers and print sum, difference, product, quotient, and remainder.

#include <iostream>
using namespace std;

int main(){
    int a, b;
    cout<< "Enter a & b: ";
    cin >> a >> b;
    cout <<"Sum of a + b is: " <<a + b << endl; 
    cout <<"difference of a - b is: " <<a - b << endl;; 
    cout <<"product of a * b is: " <<a * b << endl;; 
    cout <<"quotient of a / b is: " <<a / b << endl;; 
    cout <<"reminder of a % b is: " <<a % b << endl;; 
}
